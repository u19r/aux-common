use std::{fmt, str::FromStr};

use serde::{Deserialize, Serialize};
use sha2::{Digest as _, Sha256};
use uuid::Uuid;

use crate::{
    constants::{MAX_NAMESPACE_BYTES, MAX_OPERATION_ID_BYTES, MAX_SCOPE_BYTES},
    error::ConfigurationError,
};

fn validate_identifier(
    value: String,
    max_len: usize,
    empty_err: ConfigurationError,
    len_err: ConfigurationError,
) -> Result<String, ConfigurationError> {
    let trimmed = value.as_str();
    if trimmed.is_empty() {
        return Err(empty_err);
    }
    if trimmed.len() > max_len {
        return Err(len_err);
    }
    if !trimmed
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'_' | b'-' | b'.' | b':' | b'/'))
    {
        return Err(ConfigurationError::InvalidNamespace);
    }
    Ok(value)
}

macro_rules! impl_string_id_conversions {
    ($ty:ident) => {
        impl TryFrom<&str> for $ty {
            type Error = ConfigurationError;
            fn try_from(value: &str) -> Result<Self, Self::Error> {
                Self::try_new(value)
            }
        }
        impl TryFrom<String> for $ty {
            type Error = ConfigurationError;
            fn try_from(value: String) -> Result<Self, Self::Error> {
                Self::try_new(value)
            }
        }
        impl FromStr for $ty {
            type Err = ConfigurationError;
            fn from_str(s: &str) -> Result<Self, Self::Err> {
                Self::try_new(s)
            }
        }
        impl fmt::Display for $ty {
            fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str(&self.0)
            }
        }
    };
}

/// Validated logical writer namespace.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String")]
pub struct Namespace(String);

impl Namespace {
    pub fn try_new(value: impl Into<String>) -> Result<Self, ConfigurationError> {
        validate_identifier(
            value.into(),
            MAX_NAMESPACE_BYTES,
            ConfigurationError::EmptyNamespace,
            ConfigurationError::NamespaceTooLong,
        )
        .map(Self)
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl_string_id_conversions!(Namespace);

/// Validated tenant transaction domain scope.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String")]
pub struct TenantScope(String);

impl TenantScope {
    pub fn try_new(value: impl Into<String>) -> Result<Self, ConfigurationError> {
        validate_identifier(
            value.into(),
            MAX_SCOPE_BYTES,
            ConfigurationError::InvalidNamespace,
            ConfigurationError::InvalidNamespace,
        )
        .map(Self)
    }

    #[must_use]
    pub fn from_namespace(namespace: &Namespace) -> Self {
        Self(namespace.as_str().to_owned())
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl_string_id_conversions!(TenantScope);

/// Stable operation identity for admission deduplication and partial-write
/// tracking.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String")]
pub struct OperationId(String);

impl OperationId {
    pub(crate) fn accounted_bytes(&self) -> usize {
        std::mem::size_of::<Self>().saturating_add(self.as_str().len())
    }

    pub fn try_new(value: impl Into<String>) -> Result<Self, ConfigurationError> {
        validate_identifier(
            value.into(),
            MAX_OPERATION_ID_BYTES,
            ConfigurationError::InvalidNamespace,
            ConfigurationError::InvalidNamespace,
        )
        .map(Self)
    }

    #[must_use]
    pub fn generate_v7() -> Self {
        Self(Uuid::now_v7().to_string())
    }

    #[must_use]
    pub fn derive(namespace: &str, scope: &str, key: &str) -> Self {
        let mut hasher = Sha256::new();
        for part in [namespace.as_bytes(), scope.as_bytes(), key.as_bytes()] {
            hasher.update((part.len() as u64).to_be_bytes());
            hasher.update(part);
        }
        let digest = hasher.finalize();
        let mut hex = String::with_capacity(35);
        hex.push_str("op-");
        for byte in &digest[..16] {
            use std::fmt::Write as _;
            let _ = write!(&mut hex, "{byte:02x}");
        }
        Self(hex)
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl_string_id_conversions!(OperationId);

/// Stable UUIDv7 batch identifier generated by the engine when sealing a batch.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "Uuid")]
pub struct BatchId(Uuid);

impl BatchId {
    #[must_use]
    pub fn generate_v7() -> Self {
        Self(Uuid::now_v7())
    }

    #[must_use]
    pub const fn as_uuid(self) -> Uuid {
        self.0
    }
}

impl TryFrom<Uuid> for BatchId {
    type Error = ConfigurationError;

    fn try_from(uuid: Uuid) -> Result<Self, Self::Error> {
        if uuid.get_version_num() != 7 || uuid.get_variant() != uuid::Variant::RFC4122 {
            return Err(ConfigurationError::InvalidBatchId);
        }
        Ok(Self(uuid))
    }
}

impl fmt::Display for BatchId {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "{}", self.0)
    }
}

/// Monotonic fencing generation for buffer claims and settlement.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct FencingToken(u64);

impl FencingToken {
    #[must_use]
    pub const fn new(generation: u64) -> Self {
        Self(generation)
    }

    #[must_use]
    pub const fn generation(self) -> u64 {
        self.0
    }

    #[must_use]
    pub const fn next(self) -> Self {
        Self(self.0.saturating_add(1))
    }
}
